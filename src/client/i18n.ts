export function lang(): "en" | "de" {
  return saved.lang || (navigator.language.toLowerCase().startsWith("de") ? "de" : "en");
}

export function t(key: Key | string, vars: Record<string, string | number> = {}): string {
  const dict = lang() === "de" ? de : en;
  const s = (dict as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
